LEASE_DIR = BASE_DIR / "storage" / "leases"


def add_months(d: date, n: int) -> date:
    idx = d.year * 12 + (d.month - 1) + n
    return date(idx // 12, idx % 12 + 1, 1)


def money(x: float) -> str:
    return f"R {x:,.2f}"


