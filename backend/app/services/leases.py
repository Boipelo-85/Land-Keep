LEASE_DIR = BASE_DIR / "storage" / "leases"


def add_months(d: date, n: int) -> date:
    idx = d.year * 12 + (d.month - 1) + n
    year, month = divmod(idx, 12)
    month += 1
    return date(year, month, min(d.day, monthrange(year, month)[1]))


def money(x: float) -> str:
    return f"R {x:,.2f}"


def build_lease_pdf(lease: m.Lease, unit: m.Unit, prop: m.Property,
                    landlord: m.User, tenant: m.User) -> str:
    """Write the lease PDF and return its path relative to the backend folder."""
    LEASE_DIR.mkdir(parents=True, exist_ok=True)
    path = LEASE_DIR / f"lease_{lease.id}.pdf"
    styles = getSampleStyleSheet()
    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=22 * mm, rightMargin=22 * mm,
                            topMargin=20 * mm, bottomMargin=20 * mm, title=f"Lease agreement {lease.id}")

    details = [
        ["Landlord", landlord.full_name],
        ["Tenant", tenant.full_name],
        ["Premises", f"Unit {unit.unit_number}, {prop.name}, {prop.address}, {prop.city}"],
        ["Lease period", f"{lease.start_date:%d %B %Y} to {lease.end_date:%d %B %Y}"],
        ["Monthly rent", money(lease.monthly_rent)],
        ["Rent due", f"By day {lease.due_day} of every month"],
        ["Deposit", money(lease.deposit)],
    ]
    table = Table(details, colWidths=[40 * mm, 124 * mm])
    table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.lightgrey),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))

    clauses = [
        "The landlord lets and the tenant hires the premises for the lease period above.",
        "The tenant pays the monthly rent on or before the due day, by EFT to the landlord's nominated account.",
        "The deposit is held by the landlord and refunded after the lease ends, less any lawful deductions "
        "for damage or arrears, in line with the Rental Housing Act.",
        "The tenant keeps the premises in good condition and reports faults through LandKeep so that "
        "every request has a written, timestamped record.",
        "Either party may end the lease by giving written notice as required by law and this agreement.",
    ]
    story = [
        Paragraph("Residential lease agreement", styles["Title"]),
        Paragraph(f"Reference: LEASE-{lease.id:05d}", styles["Normal"]),
        Spacer(1, 8 * mm), table, Spacer(1, 8 * mm),
        Paragraph("Terms", styles["Heading2"]),
    ]
    story += [Paragraph(f"{i}. {text}", styles["BodyText"]) for i, text in enumerate(clauses, 1)]
    story += [
        Spacer(1, 10 * mm),
        Paragraph("Acceptance", styles["Heading2"]),
        Paragraph("The tenant accepts this lease electronically inside LandKeep. The acceptance time and "
                  "the tenant's login are recorded as the audit trail.", styles["BodyText"]),
        Spacer(1, 10 * mm),
        Paragraph("<i>Generated by LandKeep from a template for a university project. "
                  "Not legal advice: have a lawyer review the template before real use.</i>", styles["Normal"]),
    ]
    doc.build(story)
    return str(path.relative_to(BASE_DIR))


def generate_charges(db: Session, lease: m.Lease, upto: date) -> int:
    """Create monthly rent charges from the lease start up to `upto` (at least the first month)."""
    period = lease.start_date.replace(day=1)
    last = max(upto.replace(day=1), period)
    # Lock the lease so concurrent workers cannot create the same month's charge.
    db.execute(select(m.Lease).where(m.Lease.id == lease.id).with_for_update())
    existing = set(db.scalars(select(m.RentCharge.period).where(m.RentCharge.lease_id == lease.id)))
    existing.update(row.period for row in db.new if isinstance(row, m.RentCharge) and row.lease_id == lease.id)
    count = 0
    while period <= last and period <= lease.end_date:
        if period not in existing:
            db.add(m.RentCharge(lease_id=lease.id, period=period, amount_due=lease.monthly_rent,
                                due_date=max(lease.start_date, due_date_for_month(lease.due_day, period))))
            count += 1
        period = add_months(period, 1)
    return count


def generate_recurring_charges(db: Session, upto: date) -> int:
    """Catch up missing months for active leases, including downtime, without duplicates."""
    count = 0
    for lease in db.scalars(select(m.Lease).where(m.Lease.status == "active", m.Lease.start_date <= upto)):
        count += generate_charges(db, lease, upto)
    db.commit()
    return count
