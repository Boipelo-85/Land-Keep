"""Train/evaluate a local maintenance classifier. Never reads or resets the database."""
import argparse
import csv
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re

import joblib
import numpy as np
import sklearn
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, f1_score
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.pipeline import FeatureUnion, Pipeline

ROOT = Path(__file__).resolve().parent
CLASSES = ['electrical', 'general', 'plumbing', 'security']


def template_group(text):
    """Keep variants of the synthetic templates out of both sides of evaluation."""
    text = text.lower().strip()
    text = re.sub(r'^(hi, |good morning, |hello landlord, |please help: |urgent: )', '', text)
    for suffix in ['please assist.', 'can someone come and look?', 'it started last night.', 'it is getting worse.', 'thanks.', 'i have attached a photo.']:
        text = text.replace(suffix, '')
    for room in ['main bedroom', 'kitchen sink', 'bathroom basin', 'bathroom', 'bedroom', 'kitchen', 'lounge', 'passage', 'toilet', 'shower', 'bath']:
        text = re.sub(r'\b' + re.escape(room) + r'\b', '<location>', text)
    return ' '.join(re.sub(r'[^a-z<> ]', '', text).split())


def pipeline():
    return Pipeline([
        ('text', FeatureUnion([
            ('words', TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True)),
            ('characters', TfidfVectorizer(analyzer='char_wb', ngram_range=(3, 5), sublinear_tf=True)),
        ], transformer_weights={'words': 1.0, 'characters': .5})),
        ('classifier', LogisticRegression(max_iter=2000, class_weight='balanced', C=3, random_state=42)),
    ])


def read_rows(path):
    with path.open(newline='', encoding='utf-8-sig') as handle:
        rows = list(csv.DictReader(handle))
    if not rows or any(not r.get('text', '').strip() or r.get('category') not in CLASSES for r in rows):
        raise ValueError('CSV needs nonempty text and category in plumbing/electrical/security/general')
    seen = {}
    for row in rows:
        key = ' '.join(row['text'].lower().split())
        if key in seen and seen[key] != row['category']:
            raise ValueError('Conflicting labels for duplicate text; correct the CSV first')
        seen[key] = row['category']
    return rows


def metrics(model, texts, labels, class_names=None):
    class_names = class_names or CLASSES
    predicted = model.predict(texts)
    return {'rows': len(texts), 'accuracy': float(accuracy_score(labels, predicted)),
            'macro_f1': float(f1_score(labels, predicted, labels=class_names, average='macro', zero_division=0)),
            'per_class': classification_report(labels, predicted, labels=class_names, output_dict=True, zero_division=0),
            'confusion_matrix': confusion_matrix(labels, predicted, labels=class_names).tolist(),
            'label_order': class_names,
            'errors': [{'text': t, 'expected': y, 'predicted': p} for t, y, p in zip(texts, labels, predicted) if y != p]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=ROOT / 'ml/training/maintenance_synthetic.csv')
    parser.add_argument('--output', type=Path, default=ROOT / 'ml')
    parser.add_argument('--source', default='Synthetic examples generated by LandKeep seed.py; not real tenant reports')
    args = parser.parse_args()
    rows = read_rows(args.data)
    texts = np.array([r['text'].strip() for r in rows])
    labels = np.array([r['category'] for r in rows])
    groups = np.array([template_group(t) for t in texts])
    for category in CLASSES:
        if len(set(groups[labels == category])) < 4:
            raise ValueError(f'Need at least 4 distinct issue groups for {category}')
    train, test = next(StratifiedGroupKFold(n_splits=4, shuffle=True, random_state=42).split(texts, labels, groups))
    assert not set(groups[train]) & set(groups[test])
    evaluated = pipeline().fit(texts[train], labels[train])
    evaluation = metrics(evaluated, texts[test], labels[test])
    final = pipeline().fit(texts, labels)
    digest = hashlib.sha256(args.data.read_bytes()).hexdigest()
    version = 'tfidf-logreg-v2-' + digest[:12]
    metadata = {'model_version': version, 'algorithm': 'Word and character TF-IDF + trained logistic regression',
                'trained_at': datetime.now(timezone.utc).isoformat(), 'training_rows': len(rows),
                'training_groups': len(set(groups)), 'training_source': args.source,
                'data_sha256': digest, 'sklearn_version': sklearn.__version__, 'classes': CLASSES,
                'review_score_threshold': .55, 'training_counts': {c: int(sum(labels == c)) for c in CLASSES},
                'evaluation': {'method': 'Group-held-out template split; final bundled model refit on all training rows',
                               'train_rows': len(train), 'test_rows': len(test), 'template_overlap': 0, **evaluation},
                'limitations': ['Synthetic/template data; scores do not establish real-world accuracy.',
                               'Model scores are not calibrated probabilities of correctness.',
                               'Classifies text only; not a language model, diagnosis, urgency model, or rent predictor.',
                               'Emergency checks override category predictions; landlords review and correct labels.']}
    holdout = ROOT / 'ml/training/maintenance_independent.csv'
    if holdout.exists():
        independent = read_rows(holdout)
        metadata['independent_synthetic_evaluation'] = metrics(final, [r['text'] for r in independent], [r['category'] for r in independent])
    priority_model = None
    if all(row.get('urgency') in {'low', 'high'} for row in rows):
        priorities = np.array([row['urgency'] for row in rows])
        priority_eval_model = pipeline().fit(texts[train], priorities[train])
        metadata['priority_evaluation'] = metrics(priority_eval_model, texts[test], priorities[test], ['high', 'low'])
        metadata['priority_training_counts'] = {value: int(sum(priorities == value)) for value in ['high', 'low']}
        priority_model = pipeline().fit(texts, priorities)
        metadata['limitations'] = [value.replace('urgency model, or ', '') for value in metadata['limitations']]
        metadata['limitations'].append('Learned priority is advisory; deterministic emergency detection always takes priority.')
    args.output.mkdir(parents=True, exist_ok=True)
    # Only load locally generated trusted artifacts; never accept uploaded pickle files.
    target = args.output / 'maintenance_classifier.joblib'
    temporary = target.with_suffix('.tmp')
    joblib.dump({'pipeline': final, 'priority_pipeline': priority_model, 'metadata': metadata}, temporary, compress=3)
    temporary.replace(target)
    (args.output / 'maintenance_classifier.json').write_text(json.dumps(metadata, indent=2), encoding='utf-8')
    print(json.dumps({k: metadata[k] for k in ['model_version','training_rows','training_groups','training_counts','evaluation']}, indent=2))


if __name__ == '__main__':
    main()
